import { randomUUID } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { closeDatabase, connectDatabase } from '../core/db';
import { ensureIndexes } from '../core/indexes';
import { ARTICLE_CATEGORIES } from '../modules/articles/article.constants';
import { ArticleModel } from '../modules/articles/article.model';
import { hashPassword } from '../modules/auth/password.service';
import { UserModel } from '../modules/users/user.model';
import { Role } from '../shared/rbac';
import { buildSamplePdf } from '../shared/sample-pdf';

/**
 * Idempotent seeding, driven by environment variables:
 *   SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD   bootstrap the first admin (admins cannot self-register)
 *   SEED_DEMO_ARTICLES=N                     N clearly-labelled SAMPLE articles with real PDFs
 *
 * The samples use a fictional show ("Sample Podcast") on purpose: attributing invented content to
 * real podcasters would be misleading. Delete them from the admin panel once real articles exist.
 */
const SAMPLE_TOPICS = [
  'Turning a side project into a business',
  'What long-term investing looks like in practice',
  'How teams are using AI day to day',
  'Building habits that survive a busy week',
  'Lessons from a first year of founding',
  'Choosing a career path with incomplete information',
  'Why sleep and exercise are productivity tools',
  'How online communities shape culture',
];

const SAMPLE_CONTENT = [
  'This is a sample article created by the seed script so the site has something to show before you publish real content.',
  '## What a real article looks like',
  'Real articles are original write-ups of a podcast conversation: the key ideas, in your own words, with the speakers credited and a link to the original episode.',
  'Use the admin panel to upload a PDF and write the article text. Readers can read it here and download the PDF after signing in.',
  '## Next step',
  'Delete the sample articles from Manage articles and publish your first real one.',
].join('\n\n');

async function seedAdmin(): Promise<string | null> {
  const email = process.env.SEED_ADMIN_EMAIL?.trim().toLowerCase();
  const password = process.env.SEED_ADMIN_PASSWORD;
  if (!email || !password) return null;

  const existing = await UserModel.findOne({ email }).select('_id').lean();
  if (existing) {
    console.log(`admin already exists: ${email}`);
    return String(existing._id);
  }

  const admin = await UserModel.create({
    email,
    name: process.env.SEED_ADMIN_NAME ?? 'Portal Admin',
    passwordHash: await hashPassword(password),
    role: Role.ADMIN,
  });
  console.log(`admin created: ${email}`);
  return String(admin._id);
}

async function seedArticles(count: number, adminId: string): Promise<void> {
  const existing = await ArticleModel.countDocuments();
  if (existing >= count) {
    console.log(`articles already seeded (${existing})`);
    return;
  }

  const articlesDir = path.resolve(process.env.UPLOAD_DIR ?? './storage/uploads', 'articles');
  await mkdir(articlesDir, { recursive: true });

  for (let i = existing; i < count; i += 1) {
    const topic = SAMPLE_TOPICS[i % SAMPLE_TOPICS.length] as string;
    const title = `Sample: ${topic}`;
    const fileKey = `${randomUUID()}.pdf`;
    const pdf = buildSamplePdf(title, [
      'Sample article generated by the seed script.',
      'Replace it by uploading real PDFs from the admin panel.',
      `Sample number ${i + 1} of ${count}.`,
    ]);
    await writeFile(path.join(articlesDir, fileKey), pdf, { mode: 0o644 });
    await ArticleModel.create({
      title,
      summary: `A placeholder article about "${topic.toLowerCase()}". Replace it with real content.`,
      content: SAMPLE_CONTENT,
      podcastName: 'Sample Podcast',
      host: 'Demo Host',
      guest: 'Demo Guest',
      category: ARTICLE_CATEGORIES[i % (ARTICLE_CATEGORIES.length - 1)],
      tags: ['sample'],
      readingMinutes: 1,
      status: 'PUBLISHED',
      fileKey,
      fileName: `${title}.pdf`,
      fileSize: pdf.length,
      createdBy: adminId,
      publishedAt: new Date(),
    });
  }
  console.log(`seeded ${count - existing} sample article(s)`);
}

async function main(): Promise<void> {
  await connectDatabase();
  try {
    await ensureIndexes();
    const adminId = await seedAdmin();
    const articles = Number(process.env.SEED_DEMO_ARTICLES ?? 0);
    if (articles > 0) {
      if (adminId) await seedArticles(articles, adminId);
      else console.warn('skipping sample articles: no admin user');
    }
  } finally {
    await closeDatabase();
  }
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
